        WHERE (
            v_load_type = 'FULL'
            OR UPDATED_AT > v_watermark_used
        )
    ),
    deduped AS (
        SELECT * FROM ranked WHERE rn = 1
    )
    SELECT
        PART_NUMBER,
        CATEGORY,
        CERTIFICATION_STATUS,
        CREATED_AT,
        LEAD_TIME_DAYS,
        LIFECYCLE_STATUS,
        MANUFACTURER,
        REORDER_LEVEL,
        STOCK_QUANTITY,
        SUPPLIER_ID,
        UNIT_PRICE_USD,
        UPDATED_AT,
        WEIGHT_KG
    FROM deduped;

    -- ----------------------------------------------------------------
    -- 4. CAPTURE COUNTS
    -- ----------------------------------------------------------------

    -- Total source rows in scope (before dedup)
    SELECT COUNT(*)
    INTO   v_source_count
    FROM   GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_SOURCE
    WHERE (
        v_load_type = 'FULL'
        OR UPDATED_AT > v_watermark_used
    );

    -- Rows eliminated by deduplication
    v_dedup_count := v_source_count - (
        SELECT COUNT(*) FROM GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.TMP_AEROSPACE_STAGED
    );

    -- ----------------------------------------------------------------
    -- 5. RISK SCORE CALCULATION (inline in MERGE)
    --    Logic:
    --      +30  if CERTIFICATION_STATUS != 'CERTIFIED'
    --      +25  if LIFECYCLE_STATUS IN ('OBSOLETE','END_OF_LIFE')
    --      +20  if STOCK_QUANTITY < REORDER_LEVEL
    --      +15  if LEAD_TIME_DAYS > 90
    --      +10  if UNIT_PRICE_USD > 50000
    --    Capped at 100.
    -- ----------------------------------------------------------------

    -- ----------------------------------------------------------------
    -- 6. SCD TYPE 1 -- SECTION 4: Merge Logic
MERGE INTO TARGET
    -- ----------------------------------------------------------------
    MERGE INTO GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_TARGET  tgt
    USING (
        SELECT
            s.PART_NUMBER,
            s.CATEGORY,
            s.CERTIFICATION_STATUS,
            s.LEAD_TIME_DAYS,
            s.LIFECYCLE_STATUS,
            s.MANUFACTURER,
            s.REORDER_LEVEL,
            s.STOCK_QUANTITY,
            s.SUPPLIER_ID,
            s.UNIT_PRICE_USD,
            s.UPDATED_AT,
            s.WEIGHT_KG,
            -- STATUS derivation
            CASE
                WHEN s.LIFECYCLE_STATUS IN ('OBSOLETE','END_OF_LIFE') THEN 'INACTIVE'
                ELSE 'ACTIVE'
            END AS DERIVED_STATUS,
            -- RISK_SCORE derivation (capped at 100)
            LEAST(
                COALESCE(
                    CASE WHEN s.CERTIFICATION_STATUS != 'CERTIFIED'              THEN 30 ELSE 0 END
                  + CASE WHEN s.LIFECYCLE_STATUS IN ('OBSOLETE','END_OF_LIFE')   THEN 25 ELSE 0 END
                  + CASE WHEN s.STOCK_QUANTITY < s.REORDER_LEVEL                 THEN 20 ELSE 0 END
                  + CASE WHEN s.LEAD_TIME_DAYS > 90                              THEN 15 ELSE 0 END
                  + CASE WHEN s.UNIT_PRICE_USD > 50000                           THEN 10 ELSE 0 END
                , 0),
                100
            ) AS DERIVED_RISK_SCORE
        FROM GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.TMP_AEROSPACE_STAGED s
    ) src
    ON tgt.PART_NUMBER = src.PART_NUMBER

    -- UPDATE existing records (SCD Type 1 overwrite)
    WHEN MATCHED AND (
           tgt.CATEGORY             <> src.CATEGORY
        OR tgt.CERTIFICATION_STATUS <> src.CERTIFICATION_STATUS
        OR tgt.LEAD_TIME_DAYS       <> src.LEAD_TIME_DAYS
        OR tgt.LIFECYCLE_STATUS     <> src.LIFECYCLE_STATUS
        OR tgt.MANUFACTURER         <> src.MANUFACTURER
        OR tgt.REORDER_LEVEL        <> src.REORDER_LEVEL
        OR tgt.STOCK_QUANTITY       <> src.STOCK_QUANTITY
        OR tgt.SUPPLIER_ID          <> src.SUPPLIER_ID
        OR tgt.UNIT_PRICE_USD       <> src.UNIT_PRICE_USD
        OR tgt.UPDATED_AT           <> src.UPDATED_AT
        OR tgt.WEIGHT_KG            <> src.WEIGHT_KG
    ) THEN UPDATE SET
        tgt.CATEGORY             = src.CATEGORY,
        tgt.CERTIFICATION_STATUS = src.CERTIFICATION_STATUS,
        tgt.LEAD_TIME_DAYS       = src.LEAD_TIME_DAYS,
        tgt.LIFECYCLE_STATUS     = src.LIFECYCLE_STATUS,
        tgt.MANUFACTURER         = src.MANUFACTURER,
        tgt.REORDER_LEVEL        = src.REORDER_LEVEL,
        tgt.RISK_SCORE           = src.DERIVED_RISK_SCORE,
        tgt.STATUS               = src.DERIVED_STATUS,
        tgt.STOCK_QUANTITY       = src.STOCK_QUANTITY,
        tgt.SUPPLIER_ID          = src.SUPPLIER_ID,
        tgt.UNIT_PRICE_USD       = src.UNIT_PRICE_USD,
        tgt.UPDATED_AT           = src.UPDATED_AT,
        tgt.WEIGHT_KG            = src.WEIGHT_KG,
        tgt.DW_UPDATED_AT        = CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ

