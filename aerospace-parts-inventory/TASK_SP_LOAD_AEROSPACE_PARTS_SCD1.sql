        'insert_count',      v_insert_count,
        'update_count',      v_update_count,
        'dedup_count',       v_dedup_count,
        'soft_delete_count', v_soft_delete_count,
        'target_count_post', v_target_count_post,
        'execution_seconds', v_execution_seconds,
        'sla_met_flag',      v_sla_met_flag
    )::VARCHAR;

