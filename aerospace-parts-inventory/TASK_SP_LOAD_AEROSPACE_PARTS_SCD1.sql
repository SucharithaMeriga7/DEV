        CATEGORY,
        CERTIFICATION_STATUS,
        LEAD_TIME_DAYS,
        LIFECYCLE_STATUS,
        MANUFACTURER,
        REORDER_LEVEL,
        RISK_SCORE,
        STATUS,
        STOCK_QUANTITY,
        SUPPLIER_ID,
        UNIT_PRICE_USD,
        UPDATED_AT,
        WEIGHT_KG,
        DW_INSERT_TIMESTAMP,
        DW_UPDATED_AT
    ) VALUES (
        src.PART_NUMBER,
        src.CATEGORY,
        src.CERTIFICATION_STATUS,
        src.LEAD_TIME_DAYS,
        src.LIFECYCLE_STATUS,
        src.MANUFACTURER,
        src.REORDER_LEVEL,
        src.DERIVED_RISK_SCORE,
        src.DERIVED_STATUS,
        src.STOCK_QUANTITY,
        src.SUPPLIER_ID,
        src.UNIT_PRICE_USD,
        src.UPDATED_AT,
        src.WEIGHT_KG,
