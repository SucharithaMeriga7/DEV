    LEFT JOIN GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_TARGET t
           ON t.PART_NUMBER = s.PART_NUMBER
    WHERE  t.DW_INSERT_TIMESTAMP >= v_start_time;

    SELECT COUNT(*)
    INTO   v_update_count
    FROM   GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_TARGET
    WHERE  DW_UPDATED_AT  >= v_start_time
      AND  DW_INSERT_TIMESTAMP < v_start_time;

