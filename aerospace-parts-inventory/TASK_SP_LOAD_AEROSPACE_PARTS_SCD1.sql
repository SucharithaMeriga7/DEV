            CERTIFICATION_STATUS,
            CREATED_AT,
            LEAD_TIME_DAYS,
            LIFECYCLE_STATUS,
            MANUFACTURER,
            REORDER_LEVEL,
            STOCK_QUANTITY,
            SUPPLIER_ID,
            UNIT_PRICE_USD,
            UPDATED_AT,
            WEIGHT_KG,
            ROW_NUMBER() OVER (
                PARTITION BY PART_NUMBER
                ORDER BY     UPDATED_AT DESC NULLS LAST
            ) AS rn
