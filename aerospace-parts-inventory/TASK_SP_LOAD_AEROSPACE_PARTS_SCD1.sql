    v_run_id        := GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.SEQ_ETL_RUN_ID.NEXTVAL::VARCHAR;
    v_run_timestamp := CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ;
    v_start_time    := v_run_timestamp;

