    -- ----------------------------------------------------------------
    IF (v_load_type = 'FULL') THEN

        UPDATE GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_TARGET tgt
        SET    tgt.STATUS       = 'INACTIVE',
               tgt.DW_UPDATED_AT = CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ
        WHERE  tgt.STATUS != 'INACTIVE'
          AND  tgt.PART_NUMBER NOT IN (
                   SELECT PART_NUMBER
                   FROM   GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.TMP_AEROSPACE_STAGED
               );

        v_soft_delete_count := SQLROWCOUNT;

    END IF;

    -- ----------------------------------------------------------------
    -- 9. POST-LOAD TARGET COUNT
    -- ----------------------------------------------------------------
    SELECT COUNT(*)
    INTO   v_target_count_post
    FROM   GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_TARGET;

    -- ----------------------------------------------------------------
    -- 10. EXECUTION TIME & SLA CHECK  (SLA = 300 seconds / 5 minutes)
    -- ----------------------------------------------------------------
    v_end_time          := CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ;
    v_execution_seconds := DATEDIFF('second', v_start_time, v_end_time);
    v_sla_met_flag      := CASE WHEN v_execution_seconds <= 300 THEN 'Y' ELSE 'N' END;

    -- ----------------------------------------------------------------
    -- 11. WRITE RECONCILIATION LOG — SUCCESS
    -- ----------------------------------------------------------------
    -- SECTION 5: Reconciliation
INSERT INTO GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.ETL_RECONCILIATION_LOG (
        RUN_ID,
        RUN_TIMESTAMP,
        LOAD_TYPE,
        WATERMARK_USED,
        SOURCE_COUNT,
        INSERT_COUNT,
        UPDATE_COUNT,
        DEDUP_COUNT,
        SOFT_DELETE_COUNT,
        TARGET_COUNT_POST_LOAD,
        EXECUTION_SECONDS,
        SLA_MET_FLAG,
        LAST_SUCCESSFUL_RUN_TIMESTAMP,
        STATUS,
        ERROR_MESSAGE
    ) VALUES (
        v_run_id,
        v_run_timestamp,
        v_load_type,
        v_watermark_used,
        v_source_count,
        v_insert_count,
        v_update_count,
        v_dedup_count,
        v_soft_delete_count,
        v_target_count_post,
        v_execution_seconds,
        v_sla_met_flag,
        v_end_time,
        v_status,
        v_error_message
